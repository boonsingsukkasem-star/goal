-- Catalog writes return GOAL identities and never overwrite a known profile with omitted fields.
create function public.upsert_api_football_entity(p_kind text,p_payload jsonb)
returns bigint language plpgsql security definer set search_path='' as $$
declare v_id bigint; v_provider bigint := (p_payload->>'id')::bigint;
begin
 if v_provider is null or v_provider<=0 then raise exception 'Invalid upstream identity'; end if;
 if p_kind='league' then
  insert into public.football_leagues(api_football_id,name,image_url,type)
  values(v_provider,p_payload->>'name',p_payload->>'logo',p_payload->>'type')
  on conflict(api_football_id) do update set name=excluded.name,image_url=coalesce(excluded.image_url,football_leagues.image_url),type=coalesce(excluded.type,football_leagues.type)
  returning id into v_id;
 elsif p_kind='team' then
  insert into public.football_teams(api_football_id,name,image_url,short_code,founded)
  values(v_provider,p_payload->>'name',p_payload->>'logo',p_payload->>'code',nullif((p_payload->>'founded')::integer,0))
  on conflict(api_football_id) do update set name=excluded.name,image_url=coalesce(excluded.image_url,football_teams.image_url),short_code=coalesce(excluded.short_code,football_teams.short_code),founded=coalesce(excluded.founded,football_teams.founded)
  returning id into v_id;
 elsif p_kind='player' then
  insert into public.football_players(api_football_id,display_name,image_url,date_of_birth)
  values(v_provider,p_payload->>'name',p_payload->>'photo',nullif(p_payload#>>'{birth,date}','')::date)
  on conflict(api_football_id) do update set display_name=excluded.display_name,image_url=coalesce(excluded.image_url,football_players.image_url),date_of_birth=coalesce(excluded.date_of_birth,football_players.date_of_birth)
  returning id into v_id;
 else raise exception 'Unsupported entity kind'; end if;
 return v_id;
end $$;
revoke all on function public.upsert_api_football_entity(text,jsonb) from public,anon,authenticated;
grant execute on function public.upsert_api_football_entity(text,jsonb) to service_role;

create function public.ingest_api_football_fixture(payload jsonb,p_fetched_at timestamptz)
returns bigint language plpgsql security definer set search_path='' as $$
declare
 v_id bigint; v_league bigint; v_season bigint; v_home bigint; v_away bigint; v_team bigint;
 v_player bigint; v_related bigint; v_side text; v_section text; v_code text;
 v_item jsonb; v_group jsonb; v_entry jsonb; v_key text; v_keys text[] := '{}';
 v_order integer:=0; v_type integer; v_minute integer; v_extra integer;
 v_previous timestamptz; v_stored_statistics jsonb; v_status jsonb:='{}'; v_occurrences jsonb:='{}'; v_occurrence integer; v_coverage jsonb;
begin
 if (payload#>>'{fixture,id}')::bigint is null or p_fetched_at is null then raise exception 'Invalid fixture payload'; end if;
 -- Lock by provider fixture ID even for first insert; out-of-order responses cannot regress state.
 perform pg_advisory_xact_lock(hashtextextended('api-football:'||(payload#>>'{fixture,id}'),0));
 select id,provider_last_processed_at into v_id,v_previous from public.football_fixtures where api_football_id=(payload#>>'{fixture,id}')::bigint for update;
 if v_previous is not null and v_previous>p_fetched_at then return v_id; end if;
 v_league:=public.upsert_api_football_entity('league',payload->'league');
 insert into public.football_seasons(league_id,year,name,is_current)
 values(v_league,(payload#>>'{league,season}')::integer,payload#>>'{league,season}',false)
 on conflict(league_id,year) where year is not null do update set name=excluded.name returning id into v_season;
 v_home:=public.upsert_api_football_entity('team',payload#>'{teams,home}');
 v_away:=public.upsert_api_football_entity('team',payload#>'{teams,away}');
 v_code:=payload#>>'{fixture,status,short}';
 v_minute:=(payload#>>'{fixture,status,elapsed}')::integer; v_extra:=coalesce((payload#>>'{fixture,status,extra}')::integer,0);
 select coverage into v_coverage from public.football_seasons where id=v_season;
 foreach v_section in array array['events','lineups','statistics','players'] loop
  if jsonb_typeof(payload->v_section)='array' then
   v_status:=v_status||jsonb_build_object(v_section,jsonb_build_object('state',case when jsonb_array_length(payload->v_section)>0 then 'available' when v_code in ('NS','TBD') then 'pending' when v_coverage#>>array['fixtures',case v_section when 'statistics' then 'statistics_fixtures' when 'players' then 'statistics_players' else v_section end]='false' then 'unsupported' else 'empty' end,'checkedAt',p_fetched_at));
  end if;
 end loop;
 insert into public.football_fixtures(api_football_id,league_id,season_id,state_id,state_code,state_name,name,starts_at,home_score,away_score,round_name,elapsed,extra,provider_last_processed_at,data_status,detail_checked_at)
 values((payload#>>'{fixture,id}')::bigint,v_league,v_season,
 case v_code when 'NS' then 1 when '1H' then 2 when 'HT' then 3 when '2H' then 22 when 'FT' then 5 when 'ET' then 6 when 'AET' then 7 when 'PEN' then 8 when 'P' then 9 when 'PST' then 10 when 'SUSP' then 11 when 'CANC' then 12 when 'TBD' then 13 when 'WO' then 14 when 'ABD' then 15 when 'AWD' then 17 when 'INT' then 18 when 'BT' then 21 else 19 end,
 v_code,payload#>>'{fixture,status,long}',(payload#>>'{teams,home,name}')||' vs '||(payload#>>'{teams,away,name}'),(payload#>>'{fixture,date}')::timestamptz,
 (payload#>>'{goals,home}')::smallint,(payload#>>'{goals,away}')::smallint,payload#>>'{league,round}',v_minute,v_extra,p_fetched_at,v_status,case when v_status<>'{}' then p_fetched_at end)
 on conflict(api_football_id) do update set league_id=excluded.league_id,season_id=excluded.season_id,state_id=excluded.state_id,state_code=excluded.state_code,state_name=excluded.state_name,
 name=excluded.name,starts_at=excluded.starts_at,home_score=excluded.home_score,away_score=excluded.away_score,round_name=excluded.round_name,elapsed=excluded.elapsed,extra=excluded.extra,
 provider_last_processed_at=excluded.provider_last_processed_at,data_status=football_fixtures.data_status||excluded.data_status,
 detail_checked_at=coalesce(excluded.detail_checked_at,football_fixtures.detail_checked_at)
 returning id into v_id;
 foreach v_side in array array['home','away'] loop
  v_team:=case when v_side='home' then v_home else v_away end;
  insert into public.football_fixture_participants(fixture_id,team_id,location,winner)
  values(v_id,v_team,v_side,(payload#>>array['teams',v_side,'winner'])::boolean)
  on conflict(fixture_id,location) do update set team_id=excluded.team_id,winner=excluded.winner;
 end loop;
 if payload?'score' then
  delete from public.football_fixture_scores where fixture_id=v_id;
  for v_key,v_item in select key,value from jsonb_each(payload->'score') loop
   foreach v_side in array array['home','away'] loop
    insert into public.football_fixture_scores(fixture_id,team_id,type_id,description,location,goals)
    values(v_id,case when v_side='home' then v_home else v_away end,1,upper(v_key),v_side,(v_item->>v_side)::smallint);
   end loop;
  end loop;
 end if;
 if jsonb_typeof(payload->'events')='array' then
  for v_item in select value from jsonb_array_elements(payload->'events') loop
   v_order:=v_order+1;
   v_team:=case (v_item#>>'{team,id}')::bigint when (payload#>>'{teams,home,id}')::bigint then v_home when (payload#>>'{teams,away,id}')::bigint then v_away else null end;
   v_player:=null; v_related:=null;
   if (v_item#>>'{player,id}')::bigint>0 and v_item#>>'{player,name}' is not null then v_player:=public.upsert_api_football_entity('player',v_item->'player'); end if;
   if (v_item#>>'{assist,id}')::bigint>0 and v_item#>>'{assist,name}' is not null then v_related:=public.upsert_api_football_entity('player',v_item->'assist'); end if;
   v_key:=md5(jsonb_build_array(v_item->'time',v_item#>>'{team,id}',v_item#>>'{player,id}',v_item->>'type',v_item->>'detail')::text);
   v_occurrence:=coalesce((v_occurrences->>v_key)::integer,0)+1;
   v_occurrences:=v_occurrences||jsonb_build_object(v_key,v_occurrence);
   v_key:=v_key||':'||v_occurrence;
   v_keys:=array_append(v_keys,v_key);
   insert into public.football_fixture_events(fixture_id,event_key,team_id,player_id,related_player_id,type_id,type_code,type_name,minute,extra_minute,player_name,related_player_name,info,sort_order)
   values(v_id,v_key,v_team,v_player,v_related,1,
    case when v_item->>'type'='Goal' then 'GOAL' when v_item->>'type'='subst' then 'SUBSTITUTION' when v_item->>'detail'='Red Card' then 'REDCARD' when v_item->>'detail'='Yellow Card' then 'YELLOWCARD' else upper(v_item->>'type') end,
    v_item->>'detail',(v_item#>>'{time,elapsed}')::smallint,(v_item#>>'{time,extra}')::smallint,v_item#>>'{player,name}',v_item#>>'{assist,name}',v_item->>'comments',v_order)
   on conflict(fixture_id,event_key) do update set info=excluded.info,sort_order=excluded.sort_order,related_player_id=excluded.related_player_id,related_player_name=excluded.related_player_name,player_name=excluded.player_name;
  end loop;
  delete from public.football_fixture_events where fixture_id=v_id and not(event_key=any(v_keys));
 end if;
 if jsonb_typeof(payload->'lineups')='array' then
  delete from public.football_fixture_lineups where fixture_id=v_id;
  delete from public.football_fixture_formations where fixture_id=v_id;
  for v_group in select value from jsonb_array_elements(payload->'lineups') loop
   v_team:=case (v_group#>>'{team,id}')::bigint when (payload#>>'{teams,home,id}')::bigint then v_home when (payload#>>'{teams,away,id}')::bigint then v_away else null end;
   if v_team is null then continue; end if;
   if nullif(v_group->>'formation','') is not null then
    insert into public.football_fixture_formations(fixture_id,team_id,location,formation) values(v_id,v_team,case when v_team=v_home then 'home' else 'away' end,v_group->>'formation');
   end if;
   foreach v_section in array array['startXI','substitutes'] loop
    for v_entry in select value from jsonb_array_elements(coalesce(v_group->v_section,'[]')) loop
     v_item:=v_entry->'player';
     if (v_item->>'id')::bigint is null or v_item->>'name' is null then continue; end if;
     v_player:=public.upsert_api_football_entity('player',v_item);
     insert into public.football_fixture_lineups(fixture_id,team_id,player_id,type_id,player_name,jersey_number,formation_field,position_id)
     values(v_id,v_team,v_player,case when v_section='startXI' then 11 else 12 end,v_item->>'name',(v_item->>'number')::smallint,v_item->>'grid',case v_item->>'pos' when 'G' then 24 when 'D' then 25 when 'M' then 26 when 'F' then 27 end)
     on conflict(fixture_id,team_id,player_id) do nothing;
    end loop;
   end loop;
  end loop;
 end if;
 if jsonb_typeof(payload->'statistics')='array' then
  delete from public.football_fixture_statistics where fixture_id=v_id;
  v_type:=0;
  for v_group in select value from jsonb_array_elements(payload->'statistics') loop
   v_team:=case (v_group#>>'{team,id}')::bigint when (payload#>>'{teams,home,id}')::bigint then v_home when (payload#>>'{teams,away,id}')::bigint then v_away else null end;
   if v_team is null then continue; end if;
   for v_item in select value from jsonb_array_elements(v_group->'statistics') loop
    v_type:=v_type+1;
    insert into public.football_fixture_statistics(fixture_id,team_id,type_id,type_name,type_code,value)
    values(v_id,v_team,v_type,case when v_item->>'type'='expected_goals' then 'Expected Goals' else v_item->>'type' end,upper(replace(v_item->>'type',' ','_')),v_item->'value');
   end loop;
  end loop;
  if v_minute is not null and v_code in ('1H','HT','2H','ET','BT','P','LIVE','FT','AET','PEN') and jsonb_array_length(payload->'statistics')=2 then
   select coalesce(jsonb_agg(jsonb_build_object('teamId',team_id,'type',type_code,'value',value)),'[]') into v_stored_statistics from public.football_fixture_statistics where fixture_id=v_id;
   insert into public.football_stat_snapshots(fixture_id,captured_at,minute,extra,statistics) values(v_id,p_fetched_at,v_minute,v_extra,v_stored_statistics) on conflict do nothing;
   delete from public.football_stat_snapshots where fixture_id=v_id and captured_at<p_fetched_at-interval '6 hours';
  end if;
 end if;
 if jsonb_typeof(payload->'players')='array' then
  delete from public.football_fixture_player_statistics where fixture_id=v_id;
  for v_group in select value from jsonb_array_elements(payload->'players') loop
   v_team:=case (v_group#>>'{team,id}')::bigint when (payload#>>'{teams,home,id}')::bigint then v_home when (payload#>>'{teams,away,id}')::bigint then v_away else null end;
   if v_team is null then continue; end if;
   for v_entry in select value from jsonb_array_elements(v_group->'players') loop
    if (v_entry#>>'{player,id}')::bigint>0 and v_entry#>>'{player,name}' is not null then
     v_player:=public.upsert_api_football_entity('player',v_entry->'player');
