create function public.reserve_api_football_request(p_day date,p_limit integer,p_observed integer)
returns boolean language plpgsql security definer set search_path='' as $$
declare v_used integer; begin
 if p_day<>(now() at time zone 'UTC')::date or p_limit<1 or p_observed<0 then raise exception 'Invalid quota reservation'; end if;
 insert into public.football_provider_budget(day,reserved) values(p_day,p_observed) on conflict do nothing;
 select reserved into v_used from public.football_provider_budget where day=p_day for update;
 v_used:=greatest(v_used,p_observed);
 if v_used>=p_limit-5 then return false; end if;
 update public.football_provider_budget set reserved=v_used+1 where day=p_day;
 delete from public.football_provider_budget where day<p_day-7;
 return true;
end $$;
