-- Bound calendar/catalog RPC batches reduce network roundtrips without widening public access.
create function public.ingest_api_football_batch(payload jsonb,p_fetched_at timestamptz,p_kind text)
returns integer language plpgsql security definer set search_path='' as $$
declare item jsonb; n integer:=0; begin
 if jsonb_typeof(payload)<>'array' or jsonb_array_length(payload)>100 then raise exception 'Batch must contain at most 100 records'; end if;
 for item in select value from jsonb_array_elements(payload) loop
  if p_kind='fixture' then perform public.ingest_api_football_fixture(item,p_fetched_at);
  elsif p_kind='league' then perform public.ingest_api_football_league(item);
  else raise exception 'Invalid batch kind'; end if;
  n:=n+1;
 end loop; return n;
end $$;
